<script>
  $(document).ready(function() {
    function displayAppropriateVideo() {
        var landscapeVideo = $('.videoLandscape');
        var portraitVideo = $('.videoPortrait');

        if ($(window).width() <= 768) {
            landscapeVideo.hide();
            portraitVideo.show();
            landscapeVideo.each(function() {
                this.pause(); // Hentikan pemutaran
                this.currentTime = 0; // Set waktu pemutaran ke 0
            });
        } else {
            landscapeVideo.show();
            portraitVideo.hide();
            portraitVideo.each(function() {
                this.pause(); // Hentikan pemutaran
                this.currentTime = 0; // Set waktu pemutaran ke 0
            });
        }
    }

    // Panggil fungsi saat halaman dimuat
    displayAppropriateVideo();

    // Panggil fungsi saat ukuran layar berubah
    $(window).resize(displayAppropriateVideo);
  });
</script>
